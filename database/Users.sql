-- Requires the UserService-local Roles table before installation.
CREATE TABLE `Users` (
    `Id` bigint NOT NULL AUTO_INCREMENT,
    `UserId` varchar(20) NOT NULL,
    `RoleId` int NOT NULL,
    `FirstName` varchar(150) NOT NULL,
    `LastName` varchar(150) DEFAULT NULL,
    `Address1` varchar(500) NOT NULL,
    `Address2` varchar(500) DEFAULT NULL,
    `Address3` varchar(500) DEFAULT NULL,
    `Country` varchar(100) NOT NULL,
    `State` varchar(150) NOT NULL,
    `City` varchar(150) NOT NULL,
    `PinNumber` varchar(20) NOT NULL,
    `MobileNumber` varchar(30) NOT NULL,
    `AlternateMobileNumber` varchar(30) DEFAULT NULL,
    `EmailId` varchar(320) NOT NULL,
    `PasswordHash` varchar(512) DEFAULT NULL,
    `SSOProvider` varchar(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
    `SSOProviderUserId` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
    `SSOEmailId` varchar(320) DEFAULT NULL,
    `SSOProfileData` json DEFAULT NULL,
    `CreatedDate` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `UpdatedDate` datetime(6) DEFAULT NULL,
    `CreatedBy` bigint DEFAULT NULL,
    `UpdatedBy` bigint DEFAULT NULL,
    `IsActive` tinyint(1) NOT NULL DEFAULT '1',
    PRIMARY KEY (`Id`),
    UNIQUE KEY `UK_Users_UserId` (`UserId`),
    UNIQUE KEY `UK_Users_EmailId` (`EmailId`),
    UNIQUE KEY `UK_Users_SsoIdentity` (`SSOProvider`, `SSOProviderUserId`),
    KEY `IX_Users_RoleId` (`RoleId`),
    KEY `IX_Users_MobileNumber` (`MobileNumber`),
    KEY `IX_Users_SSOProviderUserId` (`SSOProvider`, `SSOProviderUserId`),
    CONSTRAINT `FK_Users_Role` FOREIGN KEY (`RoleId`) REFERENCES `Roles` (`RoleId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
